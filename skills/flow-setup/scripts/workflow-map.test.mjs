import assert from 'node:assert/strict';
import { test } from 'node:test';

import { pointers, workflowMap } from './workflow-map.mjs';

const params = {
  file: '.claude/flow.md', projectId: 'proj_1m5wbbbf1x', standingDecision: 'task_8gzt6adhhp', repos: ['acme/api', 'acme/web'],
  items: { Runtime: '`ops/runtime.md` (max runs 2)', 'Merge rule': '`docs/merge.md`; a person merges `.github/CODEOWNERS` paths', Routines: '`/flow proj_x` and `.agents/routines/` files' },
};

test('pointers: every repo path a parameter names, once, never a command or URL', () => {
  assert.deepEqual(pointers(params.items), ['ops/runtime.md', 'docs/merge.md', '.github/CODEOWNERS', '.agents/routines/']);
});

test('the fixed lines from the parameters, and the pointers the current map leaves out', () => {
  const map = workflowMap({ params, name: 'Acme', date: '2026-11-02', current: 'see `ops/runtime.md` and `.claude/flow.md`' });
  assert.equal(map.title, '# Agentic Workflow — Acme');
  assert.match(map.header, /^> Generated by `\/flow-setup` from `\.claude\/flow\.md` on 2026-11-02\./);
  assert.match(map.intro, /`proj_1m5wbbbf1x`, under the standing decision \[`task_8gzt6adhhp`\].*in `acme\/api` and `acme\/web`\./);
  assert.deepEqual(map.missing, ['docs/merge.md', '.github/CODEOWNERS', '.agents/routines/']);
});

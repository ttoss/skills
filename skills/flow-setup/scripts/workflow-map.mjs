import { existsSync, readFileSync, realpathSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

// The deterministic part of AGENTIC_WORKFLOW.md (bootstrap.md, "The workflow
// map"): its first line, its opening paragraph, and the check that every file
// a parameter points to appears in it. The diagram, the stage table and what
// each routine does are the setup's reading of the project, written by the
// model; this script never writes the file.
//
// Usage: node workflow-map.mjs [--root <repo dir>] [--date <YYYY-MM-DD>]
// Output: JSON `{ header, intro, pointers, missing }`: `missing` lists the
// pointers the current map does not name.

const here = dirname(fileURLToPath(import.meta.url));
const { load } = await import(join(here, '../../flow/scripts/params.mjs'));
const { parseFlags } = await import(join(here, '../../flow/scripts/flow-api.mjs'));

/** Every repo-relative path a parameter points to, in order, once. */
export const pointers = (items) => {
  const out = [];
  for (const value of Object.values(items)) {
    for (const m of value.matchAll(/`([^`\s]+\.(?:md|mjs|js|ts|sh|ya?ml|json))`|`(\.[\w-]+\/[^`\s]*)`/g)) {
      const path = m[1] || m[2];
      if (!out.includes(path) && !/^https?:/.test(path)) {
        out.push(path);
      }
    }
  }
  return out;
};

const list = (items) => {
  const names = items.map((r) => { return `\`${r}\``; });
  return names.length > 1 ? `${names.slice(0, -1).join(', ')} and ${names.at(-1)}` : names.join('');
};

/** The map's fixed lines and its missing pointers. */
export const workflowMap = ({ params, name, date, current = '' }) => {
  const header = `> Generated by \`/flow-setup\` from \`${params.file}\` on ${date}. Do not edit: change the parameters or the rules they point to, then run \`/flow-setup audit\`.`;
  const intro = `Work lives in the Flow project \`${params.projectId}\`, under the standing decision [\`${params.standingDecision}\`](https://flow.ttoss.dev/app/tasks/${params.standingDecision}); GitHub holds the code and its changes, in ${list(params.repos)}. It runs the ttoss [Agentic Workflow](https://ttoss.dev/docs/engineering/workflow): every run reads a task's state from Flow, acts and writes it back, so the next run starts from the graph. The tick takes what ages fastest first ([process](https://ttoss.dev/docs/engineering/workflow/process#three-rules), rule 3).`;
  const all = [params.file.split(' ')[0], ...pointers(params.items)];
  return {
    title: `# Agentic Workflow — ${name}`,
    header,
    intro,
    pointers: all,
    missing: all.filter((p) => { return !current.includes(p); }),
  };
};

const isMain = process.argv[1] && realpathSync(fileURLToPath(import.meta.url)) === realpathSync(process.argv[1]);
if (isMain) {
  try {
    const { root = '.', date = new Date().toISOString().slice(0, 10), name } = parseFlags(process.argv.slice(2));
    const params = load(root);
    const mapPath = join(root, 'AGENTIC_WORKFLOW.md');
    const current = existsSync(mapPath) ? readFileSync(mapPath, 'utf8') : '';
    const title = name || (/^# Agentic Workflow — (.+)$/m.exec(current) || [])[1] || '<project name>';
    process.stdout.write(`${JSON.stringify(workflowMap({ params, name: title, date, current }), null, 2)}\n`);
  } catch (error) {
    process.stderr.write(`${error.message}\n`);
    process.exit(1);
  }
}
